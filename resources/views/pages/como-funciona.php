        <h1>Como funciona o Desbloqueia Cursos</h1>
        <p>Você escolhe um curso, faz sua inscrição de forma simples e acompanha tudo pela sua área do aluno.</p>
        <p class="muted">O Desbloqueia Cursos foi criado para facilitar o acesso a cursos práticos, objetivos e com certificado. Em poucos passos, você conhece as opções disponíveis, escolhe a turma, realiza sua inscrição e acompanha seu aprendizado pela plataforma.</p>
    </section>

    <section class="front-section">
        <div class="page-header">
            <h2>O caminho do aluno</h2>
            <p>Veja, em ordem, como a navegação pública e a inscrição funcionam no site.</p>
        </div>

        <div class="status-grid front-card-grid">
            <article class="status-card front-card">
                <strong>1. Conheça os cursos</strong>
                <span>Você pode navegar pelo catálogo de cursos antes de criar uma conta. Em cada página de curso, veja a proposta, carga horária, descrição, público indicado, turma disponível e informações importantes antes de decidir participar.</span>
            </article>

            <article class="status-card front-card">
                <strong>2. Escolha o curso e a turma</strong>
                <span>Depois de escolher o curso, selecione a turma disponível. A turma define as condições de participação, o período, a modalidade e os demais detalhes da oferta.</span>
            </article>

            <article class="status-card front-card">
                <strong>3. Crie sua conta ou faça login</strong>
                <span>Para se inscrever, você precisa ter uma conta no site. O cadastro permite acompanhar pedidos, acessar seus cursos, consultar certificados e manter suas informações organizadas em um só lugar.</span>
            </article>

            <article class="status-card front-card">
                <strong>4. Faça sua inscrição</strong>
                <span>Na inscrição, confira os dados do curso, da turma e do participante. O sistema apresenta um resumo antes da finalização, para que você revise as informações com segurança.</span>
            </article>

            <article class="status-card front-card">
                <strong>5. Finalize o pagamento, quando houver</strong>
                <span>Alguns cursos podem exigir pagamento. Quando isso acontecer, o site orienta você até a etapa de pagamento. Após a confirmação, o acesso é liberado conforme as regras da inscrição.</span>
            </article>

            <article class="status-card front-card">
                <strong>6. Acesse sua área do aluno</strong>
                <span>Depois da inscrição, você acompanha seus cursos pela área do aluno. Nela, é possível visualizar cursos disponíveis, acessar conteúdos, acompanhar pedidos e consultar informações da sua participação.</span>
            </article>

            <article class="status-card front-card">
                <strong>7. Estude os conteúdos</strong>
                <span>Os cursos podem ter diferentes tipos de conteúdo, como textos, links, vídeos, arquivos, materiais de apoio e atividades, conforme a organização definida para cada formação.</span>
            </article>

            <article class="status-card front-card">
                <strong>8. Receba seu certificado</strong>
                <span>Quando o curso permitir certificado e os critérios forem cumpridos, você poderá acessar a certificação conforme as regras da formação. As informações sobre certificado aparecem na página do curso ou na área do aluno.</span>
            </article>
        </div>
    </section>

